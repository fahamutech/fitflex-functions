  // ── Snapshot (the ticket list) ─────────────────────────────────────────────

  const LATEST_TICKET = `(select t.id, t."tokenHash", t.status, t."revokeReason", t."displayCode" from "EventTicket" t where t."registrationId" = r.id and t.status in ('active', 'revoked') order by (t.status = 'active') desc, t."issuedAt" desc, t.id desc limit 1)`;
