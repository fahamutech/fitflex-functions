  /** GET snapshot: a full list (paged by registration id) or, with sinceSeq, only what changed since. */
  async function snapshot({ actor, organizerId, organizer = null, eventId, query = {} }) {
    if (!DESK_ROLES.includes(actor.role)) return fail('forbidden_role', 403);
    // Low: a suspended organizer may send what it already collected, but may not download the list of tickets again.
    if (organizer?.status === 'suspended') return fail('organizer_suspended', 403);
    const event = await I.eventOf(organizerId, eventId);
    if (!event) return fail('event_not_found', 404);
    const device = await ownDevice(event, query.deviceId, actor);
    if (!device) return fail('device_not_found', 404);
    const gate = buildGate(query.deskBuild ?? device.deskBuild);
    if (gate) return gate;
    if (device.status !== 'active') return fail('device_not_active', 403, { deviceStatus: device.status });
    if (!KIT_OPEN_STATUSES.includes(event.status) && event.status !== 'completed') return fail('event_not_open', 409, { eventStatus: event.status });
    const limit = parseLimit(query.limit, { dflt: 1000, max: 1000 });
    if (limit === null) return fail('invalid_limit', 400);
    const categoryId = typeof query.categoryId === 'string' && query.categoryId ? query.categoryId : null;
    if (categoryId && !(await db('EventCategory').where({ id: categoryId, eventId: event.id }).first('id'))) return fail('category_not_found', 404);
    const delta = query.sinceSeq !== undefined && query.sinceSeq !== '';
    const sinceSeq = delta ? Number(query.sinceSeq) : null;
    if (delta && (!Number.isSafeInteger(sinceSeq) || sinceSeq < 0)) return fail('invalid_cursor', 400);

    let cursor = null;
    if (query.cursor) {
      cursor = readCursor(query.cursor, device);
      if (!cursor) return fail('invalid_cursor', 400);
    }
    const first = !cursor;
    const takenAt = cursor ? new Date(cursor.t) : stamp();
    const seq = cursor ? cursor.s : await watermark(event.id);
    let rowCount = cursor ? cursor.n : null;

    if (first && !delta) {
      rowCount = Number((await rowQuery(db, event, categoryId).count({ n: '*' }).first()).n);
      if (rowCount > cfg.maxRows() && !categoryId) return fail('snapshot_too_large', 413, { rows: rowCount, max: cfg.maxRows() });
    }

    let q = rowQuery(db, event, categoryId).select('r.*', 'lt.id as _tid', 'lt.tokenHash as _hash', 'lt.status as _tstatus', 'lt.revokeReason as _treason', 'lt.displayCode as _code')
      .where('r.id', '>', cursor?.a ?? '').orderBy('r.id').limit(limit + 1);
    let removed = [];
    let pageIds = null;
    if (delta) {
      // Changed registrations of this page of ids (paged by id). Anything changed that is no longer in the list is `removed`.
      const ids = (await db('OutboxEvent').where({ eventId: event.id }).whereIn('type', FEED_TYPES).where('seq', '>', sinceSeq).where('seq', '<=', seq)
        .where('aggregateId', '>', cursor?.a ?? '').distinct('aggregateId').orderBy('aggregateId').limit(limit + 1)).map(r => r.aggregateId);
      pageIds = ids.slice(0, limit);
      q = rowQuery(db, event, categoryId).select('r.*', 'lt.id as _tid', 'lt.tokenHash as _hash', 'lt.status as _tstatus', 'lt.revokeReason as _treason', 'lt.displayCode as _code').whereIn('r.id', pageIds.length ? pageIds : ['']).orderBy('r.id');
      const hasMore = ids.length > limit;
      const regs = (await q).map(plain);
      const lateral = new Map(regs.map(r => [r.id, { tokenHash: r._hash, status: r._tstatus, revokeReason: r._treason, displayCode: r._code }]));
      const have = new Set(regs.map(r => r.id));
      removed = pageIds.filter(id => !have.has(id));
      const rows = await shapeRows(event, regs, lateral);
      await finishSnapshot({ event, device, seq, takenAt, rows: rows.length, first, delta, pageRows: rows.length });
      return pageOut({ event, device, seq, takenAt, rowCount: null, rows, removed, nextCursor: hasMore ? signCursor({ a: pageIds[pageIds.length - 1], s: seq, t: +takenAt, n: 0, d: device.id }) : null, delta: true, sinceSeq });
    }
    const fetched = (await q).map(plain);
    const page = fetched.slice(0, limit);
    const lateral = new Map(page.map(r => [r.id, { tokenHash: r._hash, status: r._tstatus, revokeReason: r._treason, displayCode: r._code }]));
    const rows = await shapeRows(event, page, lateral);
    const last = page[page.length - 1];
    const nextCursor = fetched.length > limit && last ? signCursor({ a: last.id, s: seq, t: +takenAt, n: rowCount, d: device.id }) : null;
    await finishSnapshot({ event, device, seq, takenAt, rows: rowCount, first, delta: false, pageRows: rows.length });
    return pageOut({ event, device, seq, takenAt, rowCount, rows, removed: [], nextCursor, delta: false });
  }

  async function finishSnapshot({ event, device, seq, takenAt, rows, first, delta, pageRows }) {
    if (first) await db('EventKitOfflineDevice').where({ id: device.id }).update({ snapshotSeq: seq, snapshotTakenAt: takenAt, ...(delta ? {} : { snapshotRows: rows }), updatedAt: stamp() });
    // M1: every page is audited by desk, so a scripted walk over the list is visible (the first page also records the total).
    await I.audit({ kind: 'staff', userId: device.staffUserId }, 'events.kit_offline_snapshot', event.id, null, { deviceId: device.id, rows: first ? (rows ?? 0) : undefined, pageRows, page: first ? 1 : 2, delta });
  }

  async function pageOut({ event, device, seq, takenAt, rowCount, rows, removed, nextCursor, delta, sinceSeq = null }) {
    const [points, cats] = await Promise.all([
      db('EventCollectionPoint').where({ eventId: event.id, status: 'active' }).select('id', 'name'),
      db('EventCategory').where({ eventId: event.id }).select('id', 'name'),
    ]);
    return {
      header: {
        snapshotSeq: seq, takenAt: iso(takenAt), serverTime: stamp().toISOString(), validUntil: iso(device.expiresAt), ...(delta ? { sinceSeq } : {}),
        event: { status: event.status, timezone: event.timezone, kitProvided: event.kitProvided === true },
        collectionPoints: points.map(p => ({ id: p.id, name: p.name })), categories: cats.map(c => ({ id: c.id, name: c.name })), rowCount,
      },
      rows, removed, nextCursor,
    };
  }

