      sw: { title: 'Dawati limeondolewa', body: `Dawati la bila intaneti "${d.label}" limeondolewa. Tuma skani ambazo hazijatumwa, kisha orodha iliyohifadhiwa itafutwa. ${whySw ?? `(kwa Kiingereza) ${why}`}` },
