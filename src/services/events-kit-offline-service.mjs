//
// RULE 6 AREA (owner reviews, D35). Read this file against spec §3.7 (sync rules), §3.9 (what the device proves), §3.10 (what is NOT
// trusted) and §3.15 (offline bib recording).
//
// The trust model in one paragraph: a desk is a registry row, not a credential; every call still carries the staff member's normal portal
// sign-in. The desk downloads hashes of ticket tokens and decides, offline, whether to hand a kit over; that verdict is never trusted.
// At sync the SERVER re-verifies every item itself: the token is parsed, its hash looked up, the HMAC compared in constant time against the
// registration and event, the ticket must be active (or replaced after the list was taken), the registration confirmed, the event not
// cancelled or archived, the organizer not suspended and the desk not revoked before the scan. One kit per registration is the S5
// database fact (eventkitcollection_collected_unique) and arbitrates two desks. A forged or edited cache can at worst make one desk hand
// out kits that sync then flags; it can never create an official collection.
//
// Offline bib RECORDING (D66): the number read off the physical bib is a claim. It is applied only after the handover is committed, inside a
// SAVEPOINT, by `assignOfflineBibTx`, which never replaces or releases a bib and catches only the two unique violations. It does NOT call
// the S5 `assignBibTx` (that throws refusals inside the caller's transaction and would roll back a kit handover that must stand).
//
// Nothing here stores a token, a token hash or a payload. Organizers never receive phone, email, date of birth, gender or emergency
// contact (D36, D37): snapshot rows carry a masked name, the display code, the bib and the kit state.
