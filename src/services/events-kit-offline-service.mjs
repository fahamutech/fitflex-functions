  const validItem = (it) => {
    if (!it || typeof it !== 'object') return false;
    if (typeof it.clientRef !== 'string' || !CLIENT_REF_RE.test(it.clientRef)) return false;
    if (!['scan', 'manual'].includes(it.method)) return false;
    if (it.method === 'scan' && (typeof it.payload !== 'string' || !it.payload.trim() || it.payload.length > 200)) return false;
    if (it.method === 'manual' && (typeof it.registrationId !== 'string' || !it.registrationId || it.registrationId.length > 64 || !MANUAL_REASONS.includes(it.manualReason))) return false;
    if (it.kitSize !== undefined && it.kitSize !== null && !KIT_SIZES.includes(String(it.kitSize).trim().toLowerCase())) return false;
    return true;
  };

  /** The clock rule (§3.7 rule 10): correct by the reported offset, clamp to [snapshot − tolerance, received + tolerance]. */
  function correctTime(claimedAt, offsetMs, { snapshotTakenAt, issuedAt, receivedAt }) {
    const tol = cfg.clockToleranceSeconds() * 1000;
    const claimed = +new Date(claimedAt);
    const base = Number.isFinite(claimed) ? claimed - offsetMs : +receivedAt;
    // M2: the floor is the moment the desk was registered (a scan cannot predate its desk), or the list time minus the tolerance when that is later.
    // With no list downloaded yet the floor is the desk's own issue time, never an arbitrary past instant.
    const floor = Math.max(issuedAt ? +new Date(issuedAt) : -Infinity, snapshotTakenAt ? +new Date(snapshotTakenAt) - tol : -Infinity);
    const lo = Number.isFinite(floor) ? floor : +receivedAt - tol;
    const hi = +receivedAt + tol;
    const clamped = Math.min(Math.max(base, lo), hi);
    return { at: new Date(clamped), adjusted: !Number.isFinite(claimed) || clamped !== base };
  }

  const storedResult = (row) => ({
    clientRef: row.clientRef, outcome: row.outcome, replayed: true, registrationId: row.registrationId ?? undefined, collectionId: row.collectionId ?? row.winnerCollectionId ?? undefined,
    ...(row.bibClaimed || row.bibOutcome ? { bib: { outcome: row.bibOutcome ?? 'not_applied', ...(row.bibOutcome === 'assigned' || row.bibOutcome === 'same_already' ? { number: row.bibClaimed } : {}) } } : {}),
    warnings: row.flags?.warnings ?? [], ...(row.reviewStatus === 'needs_review' ? { reviewId: row.id } : {}),
  });

  async function resolveScan(event, organizerId, payload) {
    const parts = parseToken(payload);
    if (!parts) return { outcome: 'invalid_token' };
    const token = payload.trim().startsWith(QR_PREFIX) ? payload.trim().slice(QR_PREFIX.length) : payload.trim();
    // Found by the ticket id inside the token, then the MAC and the stored hash are both checked: a tampered token is invalid_token, a
    // well-formed token for a ticket we never issued is unknown_ticket.
    const ticket = plain(await db('EventTicket').where({ id: parts.ticketId }).first());
    if (!ticket) return { outcome: 'unknown_ticket' };
    const reg = plain(await db('EventRegistration').where({ id: ticket.registrationId }).first());
    if (!reg || ticket.tokenHash !== sha256hex(token) || !verifyToken(ticketRing(), token, { registrationId: reg.id, eventId: reg.eventId })) return { outcome: 'invalid_token' };
    if (reg.eventId !== event.id) {
      const other = plain(await db('Event').where({ id: reg.eventId }).first('organizerId'));
      return { outcome: other && other.organizerId === organizerId ? 'wrong_event' : 'unknown_ticket' };
    }
    return { ok: true, reg, ticket };
  }

  /**
   * Inside the SAME transaction as the committed handover, inside a SAVEPOINT. Returns the bibOutcome string; never throws for the two unique
   * violations and never touches the collection. Never replaces or releases a bib.
   */
  async function assignOfflineBibTx(trx, { event, reg, device, bib, at, scanId, actor }) {
    const block = blockOf(device);
    if (!block) return { outcome: 'no_range' };
    if (!bibInBlock(block, bib)) return { outcome: 'out_of_range' };
    const live = plain(await trx('EventBibAssignment').where({ registrationId: reg.id }).whereNull('releasedAt').first());
    if (live) return { outcome: live.bibNumber === bib ? 'same_already' : 'registration_has_other' };
    const id = newId('ebn');
    try {
      await trx.transaction(async (sp) => {   // SAVEPOINT: a unique violation rolls back to here only
        await sp('EventBibAssignment').insert({ id, eventId: event.id, categoryId: reg.categoryId, registrationId: reg.id, bibNumber: bib, assignedBy: actor.userId, assignedAt: at, createdAt: at, sourceScanId: scanId });
        await sp('EventRegistration').where({ id: reg.id }).update({ bibNumber: bib, updatedAt: at });
      });
    } catch (err) {
      if (err.code === UNIQUE && /live_(event_)?bib_unique/.test(err.constraint ?? '')) return { outcome: 'taken' };
      if (err.code === UNIQUE && /live_registration_unique/.test(err.constraint ?? '')) return { outcome: 'registration_has_other' };
      throw err;
    }
    return { outcome: 'assigned', assignmentId: id };
  }

  async function processItem({ item, event, organizerId, organizer, device, batchId, offsetMs, receivedAt, actor }) {
    // An item without a usable clientRef cannot be stored or replayed: it is only answered.
    if (typeof item?.clientRef !== 'string' || !CLIENT_REF_RE.test(item.clientRef)) return { row: null };
    const base = { eventId: event.id, deviceId: device.id, clientRef: item.clientRef, batchId, method: ['scan', 'manual'].includes(item.method) ? item.method : 'scan', receivedAt, clockOffsetMs: offsetMs, outcomeOnDevice: text(item.outcomeOnDevice, 40) };
    const baseRow = { id: newId('eks'), ...base, flags: {}, reviewStatus: 'none', bibClaimed: null, bibOutcome: null };
    const claimed = item.bibNumber === undefined || item.bibNumber === null || item.bibNumber === '' ? null : item.bibNumber;
    const bibNorm = claimed === null ? null : normaliseBib(claimed);
    const bibKept = claimed === null ? null : (bibNorm ?? String(claimed).toUpperCase().replace(/[^A-Z0-9-]/g, '').slice(0, 12)) || null;
    baseRow.bibClaimed = bibKept;

    const save = async (trx, over) => {
      const row = { ...baseRow, ...over, flags: JSON.stringify(over.flags ?? {}) };
      if (row.outcome !== 'accepted' && row.bibClaimed) row.bibOutcome = row.bibOutcome ?? 'not_applied';
      if (REVIEW_OUTCOMES.has(row.outcome)) row.reviewStatus = 'needs_review';
      await trx('EventKitOfflineScan').insert(row);
      return row;
    };
    const finish = async (over) => save(db, over);

    if (!validItem(item)) return { row: await finish({ outcome: 'validation_failed' }) };
    const { at: correctedAt, adjusted } = correctTime(item.claimedAt, offsetMs, { snapshotTakenAt: device.snapshotTakenAt, issuedAt: device.issuedAt, receivedAt });
    const common = { claimedAt: Number.isFinite(+new Date(item.claimedAt)) ? new Date(item.claimedAt) : null, correctedAt };
    const flags = { ...(adjusted ? { clock_adjusted: true } : {}) };

    let reg; let ticket;
    if (item.method === 'scan') {
      const r = await resolveScan(event, organizerId, item.payload);
      if (!r.ok) return { row: await finish({ ...common, outcome: r.outcome, flags }) };
      ({ reg, ticket } = r);
    } else {
      reg = plain(await db('EventRegistration').where({ id: item.registrationId, eventId: event.id }).first());
      if (!reg) return { row: await finish({ ...common, outcome: 'validation_failed', flags }) };
      ticket = null;
    }
    const withReg = { ...common, registrationId: reg.id, manualReason: item.method === 'manual' ? item.manualReason : null };
    if (organizer.status === 'suspended') return { row: await finish({ ...withReg, outcome: 'organizer_suspended', flags }), reg };
    if (['cancelled', 'archived'].includes(event.status)) return { row: await finish({ ...withReg, outcome: 'event_closed', flags }), reg };
    // M2: judged by the SERVER's receipt time, never by the client's claimedAt. A desk that was removed or has expired may still SEND (so nothing
    // collected is stranded), but nothing it sends is collected automatically: every item goes to a person.
    if (device.status === 'revoked' && device.revokedAt && +receivedAt >= +new Date(device.revokedAt)) return { row: await finish({ ...withReg, outcome: 'after_revoke', flags }), reg };
    if (device.status === 'expired' || +receivedAt > +new Date(device.expiresAt)) return { row: await finish({ ...withReg, outcome: 'after_expiry', flags }), reg };

    // The point, the size and the warnings are claims too: checked against the event, never trusted.
    const warnings = [];
    let pointId = null;
    if (item.collectionPointId) {
      const p = await db('EventCollectionPoint').where({ id: String(item.collectionPointId), eventId: event.id, status: 'active' }).first('id');
      if (p) pointId = p.id; else warnings.push('collection_point_invalid');
    }
    const kitSize = item.kitSize ? String(item.kitSize).trim().toLowerCase() : null;

    for (let attempt = 0; attempt < 2; attempt += 1) {
      try {
        return await db.transaction(async (trx) => {
          const locked = plain(await trx('EventRegistration').where({ id: reg.id, eventId: event.id }).forUpdate().first());
          const live = plain(await trx('EventTicket').where({ registrationId: reg.id, status: 'active' }).first('id'));
          let revoked = !locked || locked.status !== 'confirmed' || !live;
          if (!revoked && ticket && ticket.status !== 'active') {
            // §3.7 rule 5: accepted ONLY when the ticket was replaced after the list was taken and the registration is still confirmed.
            const replacedAfter = ticket.status === 'revoked' && ticket.revokeReason === 'replaced' && ticket.revokedAt && device.snapshotTakenAt && +new Date(ticket.revokedAt) > +new Date(device.snapshotTakenAt);
            revoked = !replacedAfter;
          }
          if (revoked) return { row: await save(trx, { ...withReg, outcome: 'revoked_after_scan', flags: { ...flags, warnings } }), reg };
          const existing = plain(await trx('EventKitCollection').where({ registrationId: reg.id, status: 'collected' }).first('id'));
          if (existing) return { row: await save(trx, { ...withReg, outcome: 'duplicate', winnerCollectionId: existing.id, flags: { ...flags, warnings } }), reg };

          const collectionId = newId('ekc');
          const at = stamp();
          await trx('EventKitCollection').insert({
            id: collectionId, registrationId: reg.id, eventId: event.id, collectionPointId: pointId, status: 'collected', collectedAt: correctedAt, staffUserId: actor.userId,
            bibNumber: locked.bibNumber ?? null, kitSize: kitSize ?? locked.kitSize ?? null, method: 'offline', manualReason: item.method === 'manual' ? item.manualReason : null, offlineBatchId: batchId, createdAt: at,
          });
          const patch = { kitStatus: 'collected', updatedAt: at };
          if (kitSize) { if (!locked.kitSize) patch.kitSize = kitSize; else if (locked.kitSize !== kitSize) warnings.push('kit_size_differs'); }
          await trx('EventRegistration').where({ id: reg.id }).update(patch);
          await I.outbox(trx, event, 'kit.collected', reg.id, { registrationId: reg.id, collectionPointId: pointId, collectedAt: correctedAt });
          await I.audit(actor, item.method === 'manual' ? 'events.kit_manual_collected' : 'events.kit_collected', event.id, null, { registrationId: reg.id, collectionId, method: 'offline', deviceId: device.id, ...(item.method === 'manual' ? { manualReason: item.manualReason } : {}) }, trx);

          const row = await save(trx, { ...withReg, outcome: 'accepted', collectionId, flags: { ...flags, warnings } });
          let bib = null;
          if (bibKept) {
            bib = bibNorm ? await assignOfflineBibTx(trx, { event, reg: locked, device, bib: bibNorm, at, scanId: row.id, actor }) : { outcome: 'format_invalid' };
            const update = { bibOutcome: bib.outcome, ...(bib.assignmentId ? { bibAssignmentId: bib.assignmentId } : {}) };
            if (!NO_REVIEW_BIB.has(bib.outcome)) update.reviewStatus = 'needs_review';
            await trx('EventKitOfflineScan').where({ id: row.id }).update(update);
            Object.assign(row, update);
            if (bib.outcome === 'assigned') {
              await I.outbox(trx, event, 'bib.assigned', reg.id, { registrationId: reg.id, eventId: event.id, categoryId: reg.categoryId, bibNumber: bibNorm, previousBibNumber: null });
              await I.audit(actor, 'events.bib_assigned', event.id, null, { registrationId: reg.id, bibNumber: bibNorm, via: 'offline' }, trx);
              await I.audit(actor, 'events.kit_offline_bib_assigned', event.id, null, { registrationId: reg.id, scanId: row.id, deviceId: device.id }, trx);
            } else if (!NO_REVIEW_BIB.has(bib.outcome)) {
              await I.audit(actor, 'events.kit_offline_bib_exception', event.id, null, { outcome: bib.outcome, scanId: row.id, deviceId: device.id }, trx);
            }
          }
          return { row, reg: locked, accepted: true, bib, bibNorm };
        });
      } catch (err) {
        if (err.code === UNIQUE && /collected_unique/.test(err.constraint ?? '') && attempt === 0) continue;   // lost the race: the next pass sees the winner and records a duplicate
        throw err;
      }
    }
    return { row: await finish({ ...withReg, outcome: 'duplicate', flags }), reg };
  }

  /** POST sync: a batch of provisional scans, each item in its own transaction, oldest first. */
  async function sync({ actor, organizerId, organizer, eventId, body = {} }) {
    if (!DESK_ROLES.includes(actor.role)) return fail('forbidden_role', 403);
    const event = await I.eventOf(organizerId, eventId);
    if (!event) return fail('event_not_found', 404);
    const device = await ownDevice(event, body.deviceId, actor);
    if (!device) return fail('device_not_found', 404);
    const gate = buildGate(body.deskBuild ?? device.deskBuild);
    if (gate) return gate;
    if (!ticketRing()) return fail('tickets_unavailable', 503);
    if (!Array.isArray(body.items) || !body.items.length || typeof body.batchId !== 'string' || !BATCH_ID_RE.test(body.batchId)) return fail('invalid_batch', 400);
    if (body.items.length > cfg.syncBatch()) return fail('too_many_items', 413, { max: cfg.syncBatch() });
    const offsetRaw = Number(body.clockOffsetMs);
    const offsetMs = Number.isFinite(offsetRaw) && Math.abs(offsetRaw) <= 7 * 24 * HOUR ? Math.round(offsetRaw) : 0;
    const receivedAt = stamp();
    const started = Date.now();
    // Low: a desk cannot make the server store scans without limit (the desk's own cap is EVENTS_OFFLINE_MAX_PENDING; the server keeps 5 times that).
    const storedAlready = Number((await db('EventKitOfflineScan').where({ deviceId: device.id }).count({ n: '*' }).first()).n);
    if (storedAlready + body.items.length > cfg.maxStoredScans()) return fail('device_scan_limit', 409, { max: cfg.maxStoredScans() });

    const results = []; const summary = { accepted: 0, duplicate: 0, needsReview: 0, bibExceptions: 0, rejected: 0, deferred: 0 };
    const touched = new Map();
    let invalidTokens = 0;
    const after = [];
    for (const item of body.items) {
      const ref = typeof item?.clientRef === 'string' ? item.clientRef : null;
      if (ref) {
        const stored = plain(await db('EventKitOfflineScan').where({ deviceId: device.id, clientRef: ref }).first());
        if (stored) { results.push(storedResult(stored)); touched.set(stored.id, stored); continue; }
      }
      if (Date.now() - started > SYNC_BUDGET_MS) { results.push({ clientRef: ref, outcome: 'deferred' }); summary.deferred += 1; continue; }
      let out;
      try {
        out = await processItem({ item, event, organizerId, organizer, device, batchId: body.batchId, offsetMs, receivedAt, actor });
      } catch (err) {
        if (err.code === UNIQUE && /clientref|deviceid/i.test(`${err.constraint ?? ''}${err.detail ?? ''}`)) {   // the same scan arrived twice at once
          const stored = plain(await db('EventKitOfflineScan').where({ deviceId: device.id, clientRef: ref }).first());
          if (stored) { results.push(storedResult(stored)); continue; }
        }
        throw err;
      }
      if (!out.row) {
        results.push({ clientRef: ref ? ref.slice(0, 100) : null, outcome: 'validation_failed', replayed: false, warnings: [] });
        summary.rejected += 1;
        continue;
      }
      const row = plain(out.row);
      row.flags = typeof row.flags === 'string' ? JSON.parse(row.flags) : row.flags;
      touched.set(row.id, row);
      const res = { clientRef: row.clientRef, outcome: row.outcome, replayed: false, registrationId: row.registrationId ?? undefined, collectionId: row.collectionId ?? row.winnerCollectionId ?? undefined, warnings: row.flags?.warnings ?? [] };
      if (row.bibClaimed || row.bibOutcome) res.bib = { outcome: row.bibOutcome ?? 'not_applied', ...(row.bibOutcome === 'assigned' || row.bibOutcome === 'same_already' ? { number: row.bibClaimed } : {}) };
      if (row.reviewStatus === 'needs_review') res.reviewId = row.id;
      results.push(res);
      if (row.outcome === 'accepted') summary.accepted += 1;
      else if (row.outcome === 'duplicate') summary.duplicate += 1;
      else if (['invalid_token', 'unknown_ticket', 'wrong_event', 'validation_failed'].includes(row.outcome)) summary.rejected += 1;
      if (row.reviewStatus === 'needs_review') summary.needsReview += 1;
      if (row.outcome === 'accepted' && row.bibOutcome && !NO_REVIEW_BIB.has(row.bibOutcome)) summary.bibExceptions += 1;
      if (row.outcome === 'invalid_token') invalidTokens += 1;
      after.push({ row, out });
    }

    // Everything below happens after the items are committed and is best effort; the answer never depends on it.
    await db('EventKitOfflineDevice').where({ id: device.id }).update({ lastSyncAt: stamp(), updatedAt: stamp() }).catch(() => {});
    await I.audit(actor, 'events.kit_offline_synced', event.id, null, { deviceId: device.id, batchId: body.batchId, accepted: summary.accepted, duplicate: summary.duplicate, needsReview: summary.needsReview, rejected: summary.rejected }).catch(() => {});
    try {
      const regIds = [...new Set(results.map(r => r.registrationId).filter(Boolean))];
      if (regIds.length) {
        const regs = (await db('EventRegistration').whereIn('id', regIds)).map(plain);
        const c = await I.cardContext(event, regs);
        const cards = new Map(regs.map(r => [r.id, I.cardOf(event, r, c)]));
        for (const r of results) if (r.registrationId && cards.has(r.registrationId)) r.card = cards.get(r.registrationId);
      }
    } catch { /* cards are a convenience */ }
    for (const { row, out } of after) {
      if (row.outcome !== 'accepted') continue;
      const reg = out.reg;
      I.noticeKit(event, reg).catch(() => {});
      if (row.bibOutcome === 'assigned') I.noticeBib(event, { ...reg, bibNumber: out.bibNorm }, out.bibNorm).catch(() => {});
      I.analytics('kit_collected', { eventId: event.id, categoryId: reg.categoryId, method: 'offline', collectionPointId: null }).catch(() => {});
    }
    const count = (pred) => [...touched.values()].filter(pred).length;
    void count;
    if (summary.accepted) track('kit_offline_accepted', {}, { eventId: event.id, n: summary.accepted });
    if (summary.duplicate) track('kit_offline_duplicate', {}, { eventId: event.id, n: summary.duplicate });
    if (summary.needsReview) track('kit_offline_review', {}, { eventId: event.id, n: summary.needsReview });
    if (summary.rejected) track('kit_offline_rejected', {}, { eventId: event.id, n: summary.rejected });
    for (const { row } of after) {
      if (row.bibOutcome === 'assigned') track('kit_offline_bib_assigned', {}, { eventId: event.id });
      else if (row.outcome === 'accepted' && row.bibOutcome && !NO_REVIEW_BIB.has(row.bibOutcome)) track('kit_offline_bib_exception', { reason: row.bibOutcome }, { eventId: event.id });
    }
    if (invalidTokens > 20) {
      await I.audit(actor, 'events.kit_offline_invalid_burst', event.id, null, { deviceId: device.id, count: invalidTokens }).catch(() => {});
      track('kit_offline_invalid_burst', {}, { eventId: event.id });
      notifyTeam(organizerId, {
        id: `ntf_ekb_${device.id}_${Math.floor(+receivedAt / 3_600_000)}`, type: 'organizer_kit_offline_invalid_burst',
        en: { title: 'Offline desk sent many unrecognised tickets', body: `Desk ${device.label} sent many tickets we do not recognise. Check who is using it.` },
        sw: { title: 'Dawati limetuma tiketi nyingi zisizotambulika', body: `Dawati ${device.label} limetuma tiketi nyingi ambazo hatuzitambui. Angalia nani analitumia.` },
      }).catch(() => {});
    }
    const fresh = await loadDevice(event.id, device.id);
    return { results, summary, serverTime: stamp().toISOString(), deviceStatus: fresh?.status ?? device.status, minDeskBuild: minBuildOut() };
  }

  // ── Review ─────────────────────────────────────────────────────────────────

  async function reviewList({ actor, organizerId, eventId, query = {} }) {
    if (!MANAGE_ROLES.includes(actor.role)) return fail('forbidden_role', 403);
    const event = await I.eventOf(organizerId, eventId);
    if (!event) return fail('event_not_found', 404);
    return reviewCore(event, query);
  }
  async function reviewCore(event, query) {
    const limit = parseLimit(query.limit, { dflt: 50, max: 200 });
    if (limit === null) return fail('invalid_limit', 400);
    const status = ['needs_review', 'checked', 'manual'].includes(query.status) ? query.status : 'needs_review';
    let q = db('EventKitOfflineScan as s').join('EventKitOfflineDevice as d', 'd.id', 's.deviceId').leftJoin('EventRegistration as r', 'r.id', 's.registrationId').where('s.eventId', event.id);
    if (status === 'manual') q = q.where({ 's.method': 'manual', 's.outcome': 'accepted' });
    else q = q.where('s.reviewStatus', status);
    if (query.cursor) {
      const cur = decodeCursor(query.cursor);
      if (!Number.isFinite(cur?.t) || typeof cur?.i !== 'string' || cur.t > Date.now() + 1000 || cur.t < 0) return fail('invalid_cursor', 400);
      q = q.whereRaw('(s."receivedAt", s.id) < (?, ?)', [new Date(cur.t), String(cur.i)]);
    }
    const rows = (await q.orderBy([{ column: 's.receivedAt', order: 'desc' }, { column: 's.id', order: 'desc' }]).limit(limit + 1)
      .select('s.*', 'd.label as deviceLabel', 'r.firstName', 'r.lastName', 'r.categoryId as regCategoryId', 'r.bibNumber as regBib')).map(plain);
    const page = rows.slice(0, limit);
    const winnerIds = [...new Set(page.map(p => p.winnerCollectionId).filter(Boolean))];
    const winners = new Map(winnerIds.length ? (await db('EventKitCollection as k').leftJoin('EventKitOfflineScan as ws', 'ws.collectionId', 'k.id').leftJoin('EventKitOfflineDevice as wd', 'wd.id', 'ws.deviceId')
      .whereIn('k.id', winnerIds).select('k.id', 'k.collectedAt', 'k.method', 'wd.label as deviceLabel')).map(w => [w.id, w]) : []);
    const cats = new Map((await db('EventCategory').where({ eventId: event.id }).select('id', 'name')).map(c => [c.id, c.name]));
    const items = page.map((s) => {
      const w = s.winnerCollectionId ? winners.get(s.winnerCollectionId) : null;
      return {
        id: s.id, outcome: s.outcome, ...(s.bibOutcome ? { bibOutcome: s.bibOutcome, bibClaimed: s.bibClaimed } : {}),
        card: s.registrationId ? { displayName: cardName(s.firstName, s.lastName), categoryName: cats.get(s.regCategoryId) ?? null, bibNumber: s.regBib ?? null } : null,
        deviceLabel: s.deviceLabel, deviceTime: iso(s.claimedAt), receivedAt: iso(s.receivedAt),
        ...(w ? { winner: { collectedAt: iso(w.collectedAt), method: w.method, ...(w.deviceLabel ? { deviceLabel: w.deviceLabel } : {}) } } : {}),
        reviewStatus: s.reviewStatus, ...(s.note ? { note: s.note } : {}), method: s.method, ...(s.manualReason ? { manualReason: s.manualReason } : {}), warnings: s.flags?.warnings ?? [],
      };
    });
    const counts = await db('EventKitOfflineScan').where({ eventId: event.id }).whereIn('reviewStatus', ['needs_review', 'checked']).groupBy('reviewStatus').select('reviewStatus').count({ n: '*' });
    const by = Object.fromEntries(counts.map(c => [c.reviewStatus, Number(c.n)]));
    const last = page[page.length - 1];
    return { items, nextCursor: rows.length > limit && last ? encodeCursor({ t: +new Date(last.receivedAt), i: last.id }) : null, counts: { needsReview: by.needs_review ?? 0, checked: by.checked ?? 0 } };
  }

  async function reviewCheck({ actor, organizerId, eventId, scanId, key, body = {} }) {
    if (!MANAGE_ROLES.includes(actor.role)) return fail('forbidden_role', 403);
    const event = await I.eventOf(organizerId, eventId);
    if (!event) return fail('event_not_found', 404);
    return I.idempotent({ actor, route: `POST kit-offline/review/check|${event.id}|${scanId}`, key, body }, () => checkCore({ actor, event, scanId, body }));
  }
  async function checkCore({ actor, event, scanId, body }) {
    const s = plain(await db('EventKitOfflineScan').where({ id: String(scanId), eventId: event.id }).first());
    if (!s) return fail('scan_not_found', 404);
    if (s.reviewStatus !== 'needs_review') return fail('not_in_review', 409);
    const note = text(body.note, 300);
    if (body.note && typeof body.note === 'string' && body.note.trim().length > 300) return fail('validation_failed', 422, { fields: [{ path: 'note', code: 'tooLong' }] });
    if (s.outcome === 'revoked_after_scan' && (!note || note.length < 10)) return fail('note_required', 422, { min: 10, max: 300 });
    const at = stamp();
    const done = await db('EventKitOfflineScan').where({ id: s.id, reviewStatus: 'needs_review' }).update({ reviewStatus: 'checked', checkedBy: actor.userId, checkedAt: at, note });
    if (!done) return fail('not_in_review', 409);
    await I.audit(actor, 'events.kit_offline_checked', event.id, { reviewStatus: 'needs_review' }, { scanId: s.id, outcome: s.outcome });
    return { status: 200, review: { id: s.id, reviewStatus: 'checked', checkedAt: at.toISOString(), ...(note ? { note } : {}) } };
  }

