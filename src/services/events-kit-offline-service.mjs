  async function adminOverview({ eventId }) {
    const event = plain(await db('Event').where({ id: String(eventId) }).first());
    if (!event) return fail('event_not_found', 404);
    const items = await devicesWithCounts({ 'd.eventId': event.id });
    const counts = await db('EventKitOfflineScan').where({ eventId: event.id }).whereIn('reviewStatus', ['needs_review', 'checked']).groupBy('reviewStatus').select('reviewStatus').count({ n: '*' });
    const by = Object.fromEntries(counts.map(c => [c.reviewStatus, Number(c.n)]));
    return { items, counts: { needsReview: by.needs_review ?? 0, checked: by.checked ?? 0 } };
  }
  async function adminRevoke({ eventId, deviceId, body = {}, actorId }) {
    const event = plain(await db('Event').where({ id: String(eventId) }).first());
    if (!event) return fail('event_not_found', 404);
    return revokeCore({ event, deviceId, by: actorId, reason: body.reason, reasonSw: body.reasonSw, actorLabel: actorId });
  }

  /** The additive `offline` block of GET /kit/summary. */
  async function summaryBlock(eventId) {
    const d = await db('EventKitOfflineDevice').where({ eventId, status: 'active' }).where('expiresAt', '>', stamp()).count({ n: '*' }).sum({ pending: 'pendingReported' }).first();
    const r = await db('EventKitOfflineScan').where({ eventId, reviewStatus: 'needs_review' }).count({ n: '*' }).first();
    return { desks: Number(d.n), pendingReported: Number(d.pending || 0), needsReview: Number(r.n) };
  }

  // ── Daily purge (event-kit-offline-purge) ──────────────────────────────────

  async function purge() {
    const at = stamp();
    const expired = await db('EventKitOfflineDevice').where({ status: 'active' }).where('expiresAt', '<=', at).update({ status: 'expired', updatedAt: at });
    // A staff member who is no longer active at the organizer loses their desks (the stolen / left-the-company case).
    const gone = await db('EventKitOfflineDevice as d').where('d.status', 'active')
      .whereNotExists(db('EventOrganizerStaff as s').whereRaw('s."userId" = d."staffUserId" and s."organizerId" = d."organizerId"').where('s.status', 'active'))
      .update({ status: 'revoked', revokedAt: at, revokedBy: 'system', revokeReason: 'The staff member is no longer active at this organizer.', updatedAt: at });
    const cutoff = new Date(+at - cfg.scanKeepDays() * 86_400_000);
    const scans = await db('EventKitOfflineScan').where('receivedAt', '<', cutoff).where('reviewStatus', '<>', 'needs_review').del();
    const devices = await db('EventKitOfflineDevice as d').where('d.status', '<>', 'active').where('d.updatedAt', '<', cutoff)
      .whereNotExists(db('EventKitOfflineScan as s').whereRaw('s."deviceId" = d.id')).del();
    return { expired, revoked: gone, scans, devices };
  }

